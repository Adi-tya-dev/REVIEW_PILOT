"""GitHub inline review comment formatter with evidence grounding."""

from typing import Optional
from backend.app.schemas.ai import DefectHypothesis
from backend.app.schemas.execution import EvidenceRecord, ExecutionResult


def format_github_review_comment(
    hypothesis: DefectHypothesis,
    evidence: EvidenceRecord,
    execution_result: Optional[ExecutionResult] = None,
) -> str:
    """Format an actionable, evidence-grounded review comment for GitHub Pull Requests."""
    status_emoji = {
        "CONFIRMED_REPRODUCIBLE": "🔴 **[CONFIRMED REPRODUCIBLE DEFECT]**",
        "STATIC_WARNING": "🟡 **[STATIC ANALYSIS WARNING]**",
        "AI_HYPOTHESIS": "🔵 **[AI REVIEW HYPOTHESIS]**",
        "NEEDS_REVIEW": "⚪ **[NEEDS DEVELOPER REVIEW]**",
    }.get(evidence.status, f"**[{evidence.status}]**")

    lines = [
        f"### {status_emoji}",
        f"**Rule**: `{hypothesis.rule_id}` | **Severity**: `{hypothesis.severity}` | **Confidence**: `{evidence.confidence_score:.2f}`",
        "",
        f"**Description**: {hypothesis.description}",
        "",
    ]

    if hypothesis.suspected_trigger_input:
        lines.extend([
            "#### Trigger Input",
            f"```python\n{hypothesis.suspected_trigger_input}\n```",
            "",
        ])

    if hypothesis.expected_behavior:
        lines.extend([
            "#### Expected Behavior",
            hypothesis.expected_behavior,
            "",
        ])

    if hypothesis.suggested_test_assertion:
        lines.extend([
            "#### Target Assertion",
            f"```python\n{hypothesis.suggested_test_assertion}\n```",
            "",
        ])

    if execution_result and execution_result.execution_status in ("ASSERTION_FAILURE", "RUNTIME_EXCEPTION"):
        lines.extend([
            "#### Execution Evidence (Docker Sandbox)",
            f"- **Status**: `{execution_result.execution_status}`",
            f"- **Exception**: `{execution_result.exception_name}: {execution_result.exception_details}`",
            f"- **Execution Time**: `{execution_result.execution_time_ms} ms`",
            "",
            "<details><summary>View sandbox execution logs</summary>",
            "",
            f"```text\n{execution_result.stdout.strip() if execution_result.stdout else 'No stdout'}\n```",
            "</details>",
            "",
        ])

    lines.append("---")
    lines.append("*Generated by ReviewPilot (Evidence-grounded SLM–LLM Hybrid Code Review)*")

    return "\n".join(lines)

